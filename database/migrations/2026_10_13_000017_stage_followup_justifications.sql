CREATE TABLE IF NOT EXISTS stage_followup_justifications (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL,
    assignment_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    campaign_id BIGINT NOT NULL,
    university_etablissement_id INT NOT NULL,
    host_etablissement_id INT NOT NULL,
    type_situation ENUM('NON_DEMARRAGE','INTERRUPTION') NOT NULL,
    motif ENUM('MALADIE_INDISPONIBILITE','MOTIF_FAMILIAL','MOTIF_ACADEMIQUE','PROBLEME_ADMINISTRATIF','PROBLEME_FINANCIER','CHANGEMENT_AFFECTATION','FORCE_MAJEURE','ABANDON_VOLONTAIRE','AUTRE') NOT NULL,
    explication TEXT NULL,
    document_nom_original VARCHAR(255) NULL,
    document_nom_stockage VARCHAR(255) NULL,
    document_mime_type VARCHAR(120) NULL,
    document_taille BIGINT UNSIGNED NULL,
    document_path VARCHAR(500) NULL,
    statut ENUM('EN_ATTENTE','ACCEPTEE','REJETEE') NOT NULL DEFAULT 'EN_ATTENTE',
    submitted_by INT NOT NULL,
    submitted_at DATETIME NOT NULL,
    reviewed_by INT NULL,
    reviewed_at DATETIME NULL,
    decision_commentaire TEXT NULL,
    student_seen_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_stage_followup_uuid (uuid),
    UNIQUE KEY uq_stage_followup_assignment_student (assignment_id,student_id),
    KEY idx_stage_followup_university_status (university_etablissement_id,statut,submitted_at),
    KEY idx_stage_followup_student_status (student_id,statut,student_seen_at),
    KEY idx_stage_followup_campaign (campaign_id),
    KEY idx_stage_followup_type (type_situation)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
