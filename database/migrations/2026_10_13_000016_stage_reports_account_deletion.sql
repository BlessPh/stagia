CREATE TABLE IF NOT EXISTS stage_reports (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL,
    assignment_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    university_etablissement_id INT NOT NULL,
    version_no INT NOT NULL DEFAULT 1,
    titre VARCHAR(180) NOT NULL,
    description TEXT NULL,
    nom_original VARCHAR(255) NOT NULL,
    nom_stockage VARCHAR(255) NOT NULL,
    chemin VARCHAR(500) NOT NULL,
    mime_type VARCHAR(120) NOT NULL,
    extension VARCHAR(10) NOT NULL,
    taille BIGINT UNSIGNED NOT NULL,
    statut ENUM('SOUMIS','RECU','ACCEPTE','A_CORRIGER','REJETE','ARCHIVE') NOT NULL DEFAULT 'SOUMIS',
    commentaire_universite TEXT NULL,
    submitted_at DATETIME NOT NULL,
    received_at DATETIME NULL,
    reviewed_at DATETIME NULL,
    reviewed_by_user_id INT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_stage_reports_uuid (uuid),
    UNIQUE KEY uq_stage_reports_assignment_version (assignment_id,version_no),
    KEY idx_stage_reports_student (student_id,submitted_at),
    KEY idx_stage_reports_university (university_etablissement_id,statut),
    KEY idx_stage_reports_assignment (assignment_id,statut)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS account_deletion_requests (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    uuid CHAR(36) NOT NULL,
    user_id INT NOT NULL,
    student_id BIGINT NULL,
    statut ENUM('PENDING','CANCELLED','PROCESSED') NOT NULL DEFAULT 'PENDING',
    requested_at DATETIME NOT NULL,
    delete_after DATETIME NOT NULL,
    cancelled_at DATETIME NULL,
    processed_at DATETIME NULL,
    request_ip VARCHAR(64) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_account_deletion_uuid (uuid),
    KEY idx_account_deletion_due (statut,delete_after),
    KEY idx_account_deletion_user (user_id,statut)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
